import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const sourceUrls = [
  "https://phish.co.za/latest/phishing-domains-ACTIVE.txt",
  "https://raw.githubusercontent.com/Phishing-Database/Phishing.Database/master/phishing-domains-ACTIVE.txt"
];
const outputPath = resolve("packages/knowledge/src/generated-threats.ts");
const reportPath = resolve("data/threat-intel-report.json");
const spanishSignals = [
  "aeat", "agenciatributaria", "dgt", "trafico", "correos", "seur", "mrw", "gls",
  "bizum", "bbva", "caixa", "santander", "bankinter", "sabadell", "abanca", "unicaja",
  "kutxa", "openbank", "iberdrola", "endesa", "aemet", "seg-social", "seguridadsocial",
  "incibe", "clave", "dehu", "renfe", "movistar", "vodafone", "orange", "wallapop"
];

function normalizeDomain(line) {
  const value = line.trim().toLowerCase().replace(/^\.+|\.+$/g, "");
  if (!value || value.startsWith("#") || value.length > 253) return null;
  if (!/^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z0-9-]{2,63}$/.test(value)) return null;
  return value;
}

function isRelevantToSpain(domain) {
  return domain.endsWith(".es") || spanishSignals.some((signal) => domain.includes(signal));
}

async function fetchText(url) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 30_000);
  try {
    const response = await fetch(url, {
      signal: controller.signal,
      headers: { "User-Agent": "Lorica-Threat-Intel/0.1 (+https://github.com/guillesierra/Lorica)" }
    });
    if (!response.ok) throw new Error(`Threat feed returned HTTP ${response.status}`);
    return await response.text();
  } finally {
    clearTimeout(timeout);
  }
}

let sourceText = "";
let sourceUrl = "";
const errors = [];

for (const candidate of sourceUrls) {
  try {
    const candidateText = await fetchText(candidate);
    if (!candidateText.trim()) throw new Error("Threat feed is empty");
    sourceText = candidateText;
    sourceUrl = candidate;
    break;
  } catch (error) {
    errors.push(`${candidate}: ${error instanceof Error ? error.message : String(error)}`);
  }
}

if (!sourceText) {
  console.warn("Threat synchronization skipped; the last verified snapshot is preserved.");
  for (const error of errors) console.warn(error);
  process.exit(0);
}
const allDomains = [...new Set(sourceText.split(/\r?\n/).map(normalizeDomain).filter(Boolean))].sort();
const domains = allDomains.filter(isRelevantToSpain).slice(0, 5_000);
const generatedAt = new Date().toISOString();

const moduleText = `// Generated by scripts/sync-threat-intel.mjs. Do not edit manually.\n` +
  `export const threatSnapshot = ${JSON.stringify({
    generatedAt,
    source: "Phishing-Database/Phishing.Database",
    sourceUrl: "https://github.com/Phishing-Database/Phishing.Database",
    license: "MIT",
    status: "synced-active-feed",
    domains
  }, null, 2)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await mkdir(dirname(reportPath), { recursive: true });
await writeFile(outputPath, moduleText, "utf8");
await writeFile(reportPath, `${JSON.stringify({ generatedAt, sourceUrl, totalActiveDomains: allDomains.length, relevantDomains: domains.length, relevancePolicy: "TLD .es o token asociado a marcas/servicios españoles; no implica atribución geográfica confirmada" }, null, 2)}\n`, "utf8");

console.log(`Threat intelligence synchronized: ${domains.length}/${allDomains.length} domains retained.`);
